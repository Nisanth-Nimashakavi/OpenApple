#!/usr/bin/env node
const path = require('path');
const fs = require('fs');
const { spawn, execSync } = require('child_process');

// Forward CLI subcommands (setup, install, doctor, status, feed, serve) to Python CLI
const cliSubcommands = ['install', 'setup', 'doctor', 'status', 'feed', 'serve'];
const cmd = process.argv[2];

if (cmd && cliSubcommands.includes(cmd)) {
  const pythonArgs = cmd === 'setup' 
    ? ['-m', 'openapple.cli', 'install', 'all'] 
    : ['-m', 'openapple.cli', ...process.argv.slice(2)];
  const pyCmd = process.platform === 'win32' ? 'python' : 'python3';
  const py = spawn(pyCmd, pythonArgs, {
    cwd: path.resolve(__dirname, '..'),
    stdio: 'inherit',
  });
  py.on('error', (err) => {
    console.error('Failed to run python CLI:', err.message);
    process.exit(1);
  });
  py.on('exit', (code) => {
    process.exit(code ?? 0);
  });
  return;
}

function findElectron() {
  const isWin = process.platform === 'win32';
  const isMac = process.platform === 'darwin';

  // 1. Try resolving electron via standard require
  try {
    const loc = require('electron');
    if (loc && typeof loc === 'string' && fs.existsSync(loc)) return loc;
  } catch (e) {}

  // 2. Try reading path.txt generated by electron npm package
  const candidateDirs = [
    path.join(__dirname, '..', 'node_modules', 'electron'),
    path.join(__dirname, '..', '..', 'electron'),
    path.join(__dirname, '..', '..', '..', 'electron'),
  ];

  for (const dir of candidateDirs) {
    const pathTxt = path.join(dir, 'path.txt');
    if (fs.existsSync(pathTxt)) {
      try {
        const rel = fs.readFileSync(pathTxt, 'utf8').trim();
        const candidate = path.join(dir, 'dist', rel);
        if (fs.existsSync(candidate)) return candidate;
      } catch (e) {}
    }
  }

  // 3. Check platform specific paths in local node_modules
  const localDist = path.join(__dirname, '..', 'node_modules', 'electron', 'dist');
  if (isMac) {
    const macBin = path.join(localDist, 'Electron.app', 'Contents', 'MacOS', 'Electron');
    if (fs.existsSync(macBin)) return macBin;
  } else if (isWin) {
    const winBin = path.join(localDist, 'electron.exe');
    if (fs.existsSync(winBin)) return winBin;
  } else {
    const linBin = path.join(localDist, 'electron');
    if (fs.existsSync(linBin)) return linBin;
  }

  // 4. Try global npm root
  try {
    const npmRoot = execSync('npm root -g', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (npmRoot) {
      const gPathTxt = path.join(npmRoot, 'electron', 'path.txt');
      if (fs.existsSync(gPathTxt)) {
        const rel = fs.readFileSync(gPathTxt, 'utf8').trim();
        const gBin = path.join(npmRoot, 'electron', 'dist', rel);
        if (fs.existsSync(gBin)) return gBin;
      }
    }
  } catch (e) {}

  // 5. Try system PATH
  const whichCmd = isWin ? 'where electron' : 'which electron';
  try {
    const inPath = execSync(whichCmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split(/\r?\n/)[0].trim();
    if (inPath && fs.existsSync(inPath)) return inPath;
  } catch (e) {}

  return isWin ? 'electron.cmd' : 'electron';
}

const electronBinary = findElectron();
const appPath = path.resolve(__dirname, '..');
const args = [appPath, ...process.argv.slice(2)];

const child = spawn(electronBinary, args, {
  detached: true,
  stdio: 'ignore',
  windowsHide: true,
});

child.on('error', (err) => {
  console.error('Failed to start OpenApple:', err.message);
  console.error('Make sure Electron is installed: run "npm install" or "npm install -g electron"');
  process.exit(1);
});

child.unref();
